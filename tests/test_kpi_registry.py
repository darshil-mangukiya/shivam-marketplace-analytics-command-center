def test_render_registry_table_markdown_includes_every_kpi():
    table = render_registry_table_markdown()
    for kpi in REGISTRY:
        assert kpi.kpi_name in table
        assert kpi.output_column in table


def test_regenerate_kpi_catalog_table_is_idempotent(tmp_path, monkeypatch):
    # Regenerating twice in a row must produce byte-identical output.
    content_a = regenerate_kpi_catalog_table(write=False)
    content_b = regenerate_kpi_catalog_table(write=False)
    assert content_a == content_b


def test_kpi_catalog_markers_are_present_in_the_real_file():
    from shared.kpi_registry import KPI_CATALOG_PATH, REGISTRY_TABLE_BEGIN, REGISTRY_TABLE_END

    text = KPI_CATALOG_PATH.read_text(encoding="utf-8")
    assert REGISTRY_TABLE_BEGIN in text
    assert REGISTRY_TABLE_END in text


def test_kpi_catalog_file_on_disk_matches_current_registry():
    # The committed docs/kpi_catalog.md table must already reflect the
    # current registry -- if this fails, someone changed the registry
    # without regenerating the docs.
    from shared.kpi_registry import KPI_CATALOG_PATH

    on_disk = KPI_CATALOG_PATH.read_text(encoding="utf-8")
    assert render_registry_table_markdown() in on_disk
