"""KPI governance automation tests (Priority 2 of the final local
completion pass).

These validate *alignment* — every governed KPI actually exists in the
public output(s) it claims, its observed values respect the declared
range, its metadata marks it public-safe with no forbidden-name collision,
and docs/kpi_catalog.md still mentions it. This is metadata/presence/range
governance, not a proof that a formula can never silently diverge from its
documentation — the formulas themselves remain centralized in
shared/metrics.py, shared/profitability.py, shared/public_output_builder.py,
and shared/recommendations.py.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import pytest

from shared.kpi_registry import (
    FORBIDDEN_COLUMN_NAMES,
    REGISTRY,
    all_kpi_names,
    find_kpi,
    regenerate_kpi_catalog_table,
    render_registry_table_markdown,
    validate_documentation_references,
    validate_kpi_presence,
    validate_kpi_ranges,
    validate_public_safety,
)

PUBLIC_DIR = Path(__file__).resolve().parents[1] / "data" / "public"


def _load_real_outputs() -> dict[str, pd.DataFrame]:
    outputs = {}
    for path in PUBLIC_DIR.glob("*.csv"):
        outputs[path.stem] = pd.read_csv(path)
    return outputs


def test_registry_is_non_empty_and_names_are_unique():
    assert len(REGISTRY) >= 10
    names = all_kpi_names()
    assert len(names) == len(set(names))


def test_find_kpi_returns_none_for_unknown_name():
    assert find_kpi("Definitely Not A Real KPI") is None


def test_find_kpi_returns_the_definition():
    kpi = find_kpi("Sales Index")
    assert kpi is not None
    assert kpi.output_column == "sales_index"


def test_every_governed_kpi_has_formatting_metadata():
    for kpi in REGISTRY:
        assert kpi.format and kpi.format.strip(), f"{kpi.kpi_name} is missing format metadata"


def test_every_governed_kpi_is_marked_public_safe():
    report = validate_public_safety()
    assert report["governance_ok"].all(), report[~report["governance_ok"]]


def test_no_governed_kpi_collides_with_forbidden_column_names():
    for kpi in REGISTRY:
        assert kpi.output_column not in FORBIDDEN_COLUMN_NAMES


def test_every_governed_kpi_is_documented_in_kpi_catalog():
    report = validate_documentation_references()
    assert report["documented"].all(), report[~report["documented"]]


