@pytest.fixture(scope="module")
def real_outputs() -> dict[str, pd.DataFrame]:
    outputs = _load_real_outputs()
    if not outputs:
        pytest.skip("data/public/*.csv not present — run the pipeline first")
    return outputs


def test_every_governed_kpi_column_exists_in_at_least_one_real_output(real_outputs):
    report = validate_kpi_presence(real_outputs)
    missing = report[~report["present"]]
    assert missing.empty, f"KPIs with no matching column in any real public output: {missing['kpi_name'].tolist()}"


def test_no_governed_kpi_output_is_missing_from_an_output_that_claims_it(real_outputs):
    # A KPI claiming to appear in an output that DOES exist on disk must
    # genuinely carry that column -- this catches a KPI/output going stale
    # after a future refactor (Requirement 29: "no stale KPI name remains").
    report = validate_kpi_presence(real_outputs)
    stale = report[report["missing_from"].map(bool)]
    assert stale.empty, f"KPIs claiming an output that no longer carries the column: {stale.to_dict('records')}"


def test_numeric_kpi_values_fall_within_expected_range_on_real_data(real_outputs):
    report = validate_kpi_ranges(real_outputs)
    assert not report.empty
    out_of_range = report[~report["in_range"]]
    assert out_of_range.empty, f"KPI values outside expected range: {out_of_range.to_dict('records')}"


def test_no_undocumented_core_kpi_column_silently_introduced(real_outputs):
    # Every registry output_column that appears anywhere in the real data
    # must be exactly the column name declared -- guards against a rename
    # (e.g. sales_index -> salesIndex) going unnoticed by the registry.
    for kpi in REGISTRY:
        for output_name in kpi.source_outputs:
            if output_name not in real_outputs:
                continue
            columns = set(real_outputs[output_name].columns)
            # A close-but-not-exact match (case/underscore drift) would be
            # invisible to a plain "in columns" check, so also assert no
            # near-miss variant exists unless the exact name is present.
            if kpi.output_column not in columns:
                near_misses = [c for c in columns if c.lower().replace("_", "") == kpi.output_column.lower().replace("_", "")]
                assert not near_misses, (
                    f"{kpi.kpi_name}: expected column '{kpi.output_column}' not found in {output_name}, "
                    f"but a near-miss variant exists: {near_misses} -- registry is stale"
                )


